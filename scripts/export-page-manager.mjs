import {mkdir,cp,readFile,writeFile} from 'node:fs/promises';
import {execFileSync} from 'node:child_process';
import {resolve,dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
import {buildPageManagerAssets} from '../packages/page-manager/scripts/build.mjs';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..'),packageRoot=resolve(root,'packages/page-manager');
const manifest=JSON.parse(await readFile(resolve(packageRoot,'package.json'),'utf8'));
const destination=resolve(root,'artifacts/page-manager-kit-v'+manifest.version);
await buildPageManagerAssets();
await mkdir(destination+'/starter/api',{recursive:true});
await mkdir(destination+'/starter/vendor',{recursive:true});
const npmCli=process.env.npm_execpath;
if(!npmCli)throw new Error('Run through npm run export:manager');
const packed=JSON.parse(execFileSync(process.execPath,[npmCli,'pack','--ignore-scripts','--json','--pack-destination',destination],{cwd:packageRoot,encoding:'utf8'}));
const tarball=packed[0].filename;
const files=['package.json','README.md','page-manager.config.js','website.js','server.mjs','build.mjs','vercel.json','.env.example','.gitignore','api/index.js'];
for(const file of files)await cp(resolve(root,'examples/page-manager-starter',file),resolve(destination,'starter',file));
const starter=JSON.parse(await readFile(destination+'/starter/package.json','utf8'));
await cp(resolve(destination,tarball),resolve(destination,'starter/vendor',tarball));
starter.dependencies['@mcg/page-manager']='file:./vendor/'+tarball;
await writeFile(destination+'/starter/package.json',JSON.stringify(starter,null,2)+'\n');
await cp(packageRoot+'/README.md',destination+'/사용방법.md');
await writeFile(destination+'/VERSION.json',JSON.stringify({name:'@mcg/page-manager',version:packed[0].version,sha512:packed[0].integrity,tarball},null,2)+'\n');
console.log('Reusable manager kit: '+destination+'\nInstallable package: '+tarball);
